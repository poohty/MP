export type StarterRecipeData = {
  name: string;
  category: RecipeCategory;
  ingredients: string[];
  instructions: string[];
  prepTime: string;
  cookTime: string;
  totalTime: string;
  calories: string;
  sourceUrl?: string;
};

function buildContent(r: StarterRecipeData): string {
  const ing = r.ingredients.map(i => `- ${i}`).join('\n');
  const ins = r.instructions.map((s, i) => `☐ ${i + 1}. ${s}`).join('\n');
  const times = `Prep Time: ${r.prepTime}\nCook Time: ${r.cookTime}\nTotal Time: ${r.totalTime}`;
  const nutrition = `Calories: ${r.calories} per serving`;
  return `**Ingredients:**\n${ing}\n\n**Nutritional Facts:**\n${nutrition}\n\n**Times:**\n${times}\n\n**Instructions:**\n${ins}`;
}

